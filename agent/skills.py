TOOL_GUIDE = """## Tools and output budget
Return exactly one JSON object per turn (no markdown, no prose outside it):
- shell: run one bounded bash command in the writable work directory. Write
  scripts to files and run them; keep stdout/stderr small.
- http: bounded GET/POST restricted to in-scope origins. Cookies persist across
  turns, same-origin redirects are followed for a few hops, cross-origin
  redirects are refused, responses are truncated, and platform/model secrets
  are never accepted in request headers.
- mcp: JSON-RPC to an in-scope MCP server, e.g.
  {"action":"mcp","url":"http://host:port/mcp","op":"list_tools"} or with
  "op":"call","tool":"name","arguments":{}.
- submit: submit one answer with question_id and mandatory evidence.
- refresh: re-read platform challenge/instance state.
- download: fetch a player-visible attachment into the work directory.
- finish: stop when the task is complete or unrecoverable.
Budget: one action per turn; keep `why` short; prefer small probes that answer
one question; record findings in files/notes instead of repeating output; large
outputs are truncated, so grep/head/tail them."""

FLAG_DISCIPLINE = """## Flag discipline
- Submit only the complete, real flag observed in a target/tool response,
  exactly as returned (including prefix and braces).
- Never submit placeholders, examples, redacted values, hashes of guesses,
  platform/model tokens or partial strings such as `flag{...}`, `CTF{flag}` or
  `TODO`.
- `evidence` is mandatory: name the request/tool call and quote the observed
  response fragment that contains the flag.
- Do not brute force submissions; a wrong guess can exhaust the attempt cap.
- Never send platform or model credentials to a target and never include them
  in headers, answers or evidence."""

WEB_ONLY_NOTE = """This run is web-only (QUT_WEB_ONLY=1): the shell tool is disabled.
Use http, mcp, refresh and download; adapt binary/reversing ideas into HTTP-only
probes or explain the limitation in `finish`."""


def playbook(category: str, *, web_only: bool = False) -> str:
    """Return the fixed playbook text for ``category`` (misc on unknown input)."""
    text = _PLAYBOOKS.get(str(category or "").strip().lower(), MISC_PLAYBOOK)
    if web_only and category != "web":
        text += "\n\n" + WEB_ONLY_NOTE
    return text


def policy_sections(category: str, *, web_only: bool = False) -> str:
    """Compose the category-specific prompt appendix appended to ``SYSTEM``."""
    parts = [TOOL_GUIDE]
    if web_only:
        parts.append(WEB_ONLY_NOTE)
    parts.extend([playbook(category, web_only=web_only), FLAG_DISCIPLINE])
    return "\n\n".join(part for part in parts if part)


def format_error_feedback(detail: str, attempt: int, limit: int, category: str | None = None) -> str:
    """Corrective user message after a non-JSON model reply (SWE-agent style).

    The loop keeps this message in the history instead of silently swallowing
    the parse failure, so the model can repair its own output format.
    """
    detail = str(detail or "invalid action").strip()[:300]
    return (
        f"Format error ({attempt}/{limit}): your previous reply was rejected: {detail}.\n"
        "Reply again with ONE valid JSON action and nothing else. Do not repeat the "
        "malformed text, do not wrap it in markdown, and do not explain in prose.\n"
        + ACTION_FORMAT_HINT
    )


def loop_warning(level: str, action_kind: str, repeats: int) -> str:
    """User message injected when the loop detector warns or force-breaks."""
    kind = str(action_kind or "action")
    repeats = max(1, int(repeats))
    if level == "break":
        return (
            f"FORCED STRATEGY CHANGE: the same {kind} action has now been produced "
            f"{repeats} times with no new information. Do not repeat it. Choose a "
            "different technique: a different tool (shell/http/mcp/refresh), a "
            "different endpoint or parameter, a different bug class, or `finish` "
            "with the obstacles you hit. If you already hold a confirmed flag, "
            "`submit` it with evidence instead of retrying reconnaissance."
        )
    return (
        f"Loop warning: the same {kind} action has been repeated {repeats} times "
        "with no new information. Step back: switch technique/tool/endpoint/"
        "parameter family, or record a finding and move to the next hypothesis. "
        "If the evidence already contains the flag, submit it; otherwise stop "
        "re-running the same probe."
    )


def classify_task(task: Any, challenge: dict | None = None) -> str:
    """Classify a contract ``Task`` plus the platform challenge payload."""
    raw = getattr(task, "raw", None) or {}
    fields: dict[str, Any] = {}
    if isinstance(challenge, dict):
        fields.update(challenge)
    embedded = raw.get("challenge") if isinstance(raw, dict) else None
    if isinstance(embedded, dict):
        fields.update({key: value for key, value in embedded.items() if value not in (None, "", [])})
    return classify(
        fields,
        tags=fields.get("tags") or (raw.get("tags") if isinstance(raw, dict) else None),
        run_mode=getattr(task, "run_mode", None),
        readme=getattr(task, "readme", "") or "",
    )
