"""Challenge classification and category playbooks for the single-agent solver.

This module is deliberately *guidance only*: it produces prompt text that tells
the model which techniques to try and which evidence to collect. It never
executes anything, never holds challenge credentials and does not hard-code a
payload library - concrete payloads are generated by the model against the live
in-scope target, as required by the competition rules.

Borrowed ideas (see ``docs/solver-skills.md`` for the full mapping):

* SWE-agent v0.7 ``config/ctf/*`` - category-specific system/instance templates,
  command documentation, ``Last5Observations`` history trimming and the
  ``submit``/``exit_forfeit`` terminal commands.
* ctf-agent - ``ChallengeMeta`` based classification, flag discipline (never
  trust placeholder flags), ``LoopDetector`` warn/break thresholds (3/5) and
  format-error feedback instead of silent parse failures.
* Koshary - per-category ``web.txt``/``pwn.txt`` prompt structure and the
  ``fullpwn.md`` service-discovery to privilege-escalation kill chain.
* AWE - for each Web bug class a "baseline, then confirm/verify" detector loop
  instead of spraying payloads; detection results must cite a real differential.
* PwnAI - ``reversing -> debugging -> exploitation`` pipeline: triage, static
  analysis, dynamic analysis, offset, leak, local exploit, then remote.
"""
