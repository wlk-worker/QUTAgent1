def _alias(value: Any) -> str | None:
    if value is None:
        return None
    text = str(value).strip().lower().strip("\"'")
    text = re.sub(r"[\s/_\-]+", " ", text)
    if not text:
        return None
    if text in CATEGORY_ALIASES:
        return CATEGORY_ALIASES[text]
    # A few platforms use compound labels such as "Web - SQLi".
    for alias, category in CATEGORY_ALIASES.items():
        if len(alias) >= 4 and re.search(r"\b" + re.escape(alias) + r"\b", text):
            return category
    return None


def _tag_list(tags: Any) -> list[str]:
    if tags is None:
        return []
    if isinstance(tags, str):
        tags = re.split(r"[,;]", tags)
    if not isinstance(tags, Iterable):
        return []
    values = []
    for tag in tags:
        if isinstance(tag, (str, int, float)) and str(tag).strip():
            values.append(str(tag).strip())
    return values


def classify(
    challenge: dict | None = None,
    *,
    category: Any = None,
    tags: Any = None,
    description: Any = None,
    name: Any = None,
    readme: str = "",
    run_mode: str | None = None,
) -> str:
    """Return one of ``web``, ``pwn``, ``ai``, ``misc`` or ``qa``.

    Priority: QA run mode (the platform quiz format decides the interaction),
    then an explicit known platform category, then weighted keyword scoring over
    tags/name/category/description/README with ``misc`` as the safe default.
    The function is deterministic and has no I/O.
    """
    fields = dict(challenge) if isinstance(challenge, dict) else {}
    category = category if category is not None else fields.get("category")
    tags = tags if tags is not None else fields.get("tags")
    description = description if description is not None else fields.get("description")
    name = name if name is not None else fields.get("name")
    if run_mode == "qa":
        return "qa"
    resolved = _alias(category)
    if resolved:
        return resolved

    texts = {
        "tags": " ".join(_tag_list(tags)).lower(),
        "name": str(name or "").lower(),
        "category": str(category or "").lower(),
        "description": str(description or "").lower()[: _READ_LIMIT * 2],
        "readme": str(readme or "")[:_READ_LIMIT].lower(),
    }
    scores = {bucket: 0 for bucket in ("web", "pwn", "ai", "misc")}
    for bucket, patterns in _TEXT_TERMS.items():
        for pattern in patterns:
            for field, weight in _FIELD_WEIGHTS.items():
                if texts[field] and re.search(pattern, texts[field]):
                    scores[bucket] += weight
    best = max(("web", "pwn", "ai", "misc"), key=lambda item: scores[item])
    return best if scores[best] > 0 else "misc"


